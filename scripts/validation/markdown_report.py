"""Write the automated section of docs/validation_report.md, keeping everything else."""
from __future__ import annotations

from pathlib import Path

from scripts.atomic_write import write_atomic
from scripts.checks import CheckResult

START = "<!-- automated-validation:start -->"
END = "<!-- automated-validation:end -->"


def cell(text: object) -> str:
    """Make text safe inside a Markdown table cell."""
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(
    generated_at: str,
    files: list[tuple[str, int, str]],
    results: dict[str, list[CheckResult]],
    missing: list[tuple[str, str, int, int]],
) -> str:
    """Return the automated section as Markdown."""
    all_results = [r for rs in results.values() for r in rs]
    failed = sum(not r.passed for r in all_results)
    lines = [
        START,
        "## Automated checks",
        "",
        f"Generated by `python -m scripts.validate_data` at {generated_at} (UTC). Do not edit this section by hand.",
        "",
        f"**Result: {'PASS' if not failed else 'FAIL'}**, {len(all_results) - failed} of {len(all_results)} checks passed.",
        "",
        "| File | Bytes | SHA-256 |",
        "|------|------:|---------|",
        *[f"| {name} | {size:,} | `{sha[:16]}` |" for name, size, sha in files],
        "",
        "| Table | Check | Result | Detail |",
        "|-------|-------|--------|--------|",
        *[
            f"| {table} | {cell(r.name)} | {'PASS' if r.passed else '**FAIL**'} | {cell(r.detail)} |"
            for table, rs in results.items() for r in rs
        ],
        "",
        "Missing values (blank cells) by column:",
        "",
        "| Table | Column | Missing | Rows |",
        "|-------|--------|--------:|-----:|",
        *([f"| {t} | {c} | {n} | {rows} |" for t, c, n, rows in missing] or ["| - | - | 0 | - |"]),
        END,
    ]
    return "\n".join(lines)


def update(report_path: Path, section: str) -> None:
    """Replace the automated section in the report, or add it after the title if absent."""
    text = report_path.read_text(encoding="utf-8") if report_path.exists() else "# Validation report\n"
    if START in text and END in text:
        before, rest = text.split(START, 1)
        text = before + section + rest.split(END, 1)[1]
    else:
        title, _, body = text.partition("\n")
        text = f"{title}\n\n{section}\n{body}"
    write_atomic(report_path, text.encode("utf-8"))
